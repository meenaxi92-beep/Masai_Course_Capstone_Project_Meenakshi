# Task 2 - generate_scr_narrative(findings: dict)

def generate_scr_narrative(findings: dict) -> dict:

    system_instruction = """
You are a Data Analyst on Mamaearth's Growth Analytics Team.
Audience: Head of Data Analytics.

Write a concise, professional business narrative using the SCR framework.
Use exactly three labeled sections:
SITUATION
COMPLICATION
RESOLUTION

Maximum length: 210 words.

Evidence and accuracy rules:
- Use only facts and numbers present in the findings dictionary.
- Do not invent statistics, causes, correlations, or business outcomes.
- Preserve all numerical values and their meaning.
- Format INR currency values consistently to two decimal places.
- Include sample sizes when discussing small or high-risk segments.
- Specifically, state that the Tier 2 high-value COD result is
  7 returns out of 8 orders, if these figures are provided.
- Describe findings as observed patterns, not proof of causation.
- Do not claim that a recommendation will definitely reduce returns,
  increase revenue, or reduce costs.
- Clearly distinguish verified results from proposed actions.
- Make recommendations measurable and suitable for a pilot.

Return only the three labeled narrative sections.
Do not include JSON, introductory text, or a conclusion outside SCR.
"""


    user_prompt = f"""
      Write a concise business story using these verified findings:

      {json.dumps(findings, indent=2)}

      SITUATION:
      Approximately 30-40 words.
      Introduce the cleaned revenue baseline and the purpose of the
      analytics pipeline. Avoid unsupported claims about business performance.

      COMPLICATION:
      Approximately 70-90 words.
      Explain:
      - The revenue reconciliation difference associated with duplicate records.
      - Return-rate differences across COD, CARD, and UPI.
      - The highest-risk COD city-tier segment.
      - The high-value COD finding across city tiers.
      - Include the sample size for the Tier 2 high-value segment.

      RESOLUTION:
      Approximately 50-70 words.
      Explain the corrected monthly revenue trend and the true peak month.
      Recommend a measurable pilot for high-value COD orders in Tier 2 cities.
      Mention that additional data is needed to validate the observed pattern.
      Do not present the recommendation as a proven solution.

      Keep all three sections within 210 words.
      Use the exact labels SITUATION, COMPLICATION, and RESOLUTION.
      """


    # Task 3 - Parameter locking and error handling
    try:
        response = client.models.generate_content(
            model="gemini-3.1-flash-lite",
            contents=user_prompt,
            config=types.GenerateContentConfig(
                system_instruction=system_instruction,
                temperature=0.0,
                max_output_tokens=400
            )
        )


        if not response.text:
            return {
                "status": "error",
                "success": False,
                "narrative": None,
                "message": "Empty response"
            }

        return {
            "status": "success",
            "narrative": response.text,
            "tokens": (
                response.usage_metadata.total_token_count
                if response.usage_metadata else None
            )
        }

    except Exception as err:
        return {
            "status": "error",
            "success": False,
            "narrative": None,
            "message": str(err)
        }


