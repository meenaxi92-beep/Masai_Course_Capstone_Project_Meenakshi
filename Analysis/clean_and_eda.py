##	Task 6 - IQR outlier detection on quantity

# Calculate Q1, Q3 and IQR for quantity
q1, q3 = np.percentile(orders_clean['quantity'], [25, 75])
iqr = q3 - q1

lower_bound = q1 - 1.5 * iqr
upper_bound = q3 + 1.5 * iqr

print("-- IQR Outlier Detection --")
print("Q1:", q1)
print("Q3:", q3)
print("IQR:", iqr)
print("Lower Bound:", lower_bound)
print("Upper Bound:", upper_bound)

# Identify outliers
orders_clean['is_outlier'] = (
    (orders_clean['quantity'] < lower_bound) |
    (orders_clean['quantity'] > upper_bound)
)

# Print outlier rows without dropping the rows
print("\n -- Outlier Orders --")
print(orders_clean.loc[orders_clean['is_outlier'], ['order_id', 'quantity']])

