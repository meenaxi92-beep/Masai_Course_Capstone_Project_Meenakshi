## Task 3 - Remove duplicate orders

# Identify duplicates using the natural key.
# order_id is excluded because O0176-O0180 have different IDs by design.
duplicate_mask = orders.duplicated(
    subset=[
        'customer_id', 'product_id', 'order_date', 'quantity',
        'discount_pct', 'payment_method', 'rating', 'returned'
    ],
    keep='first'
)

# Print the duplicate order IDs
print("DUPLICATE ORDER IDs:")
print(orders.loc[duplicate_mask, 'order_id'])

# Remove duplicate rows
orders_clean = orders[~duplicate_mask].copy()

# Check the cleaned shape
print("CLEANED DATA SHAPE:", orders_clean.shape)

## Task 4 - Impute missing values

# Fill missing discount values with 0
orders_clean['discount_pct'] = orders_clean['discount_pct'].fillna(0)

# Calculate median rating before imputation
rating_median = orders_clean['rating'].median()
print("MEDIAN RATING:", rating_median)

# Count the rows which were missing the values for imputation
print("--- Missing Values Before Imputation ---")
print(orders[['discount_pct', 'rating']].isnull().sum())

# Fill missing ratings with the median
orders_clean['rating'] = orders_clean['rating'].fillna(rating_median)

# Check for remaining missing values
print("--- Missing Values After Imputation ---")
print(orders_clean[['discount_pct', 'rating']].isnull().sum())

## Task 5 - Merge and reconcile against Part 1

# Merge orders with products
orders_clean = pd.merge(orders_clean, products,
    on='product_id', how='left'
)

# Merge orders with customers
orders_clean = pd.merge(orders_clean, customers,
    on='customer_id', how='left'
)

# Calculate order value after discount
orders_clean['order_value'] = (
    orders_clean['quantity'] * orders_clean['price'] * (1 - orders_clean['discount_pct'] / 100)
)

# Calculate total cleaned revenue
cleaned_revenue = orders_clean['order_value'].sum()

print("CLEANED TOTAL ORDER VALUE:", round(cleaned_revenue, 2))

# Get the 5 duplicate rows that were removed
dropped_orders = orders.loc[duplicate_mask].copy()

# Merge dropped orders with products to get price
dropped_orders = pd.merge(
    dropped_orders, products[['product_id', 'price']],
    on='product_id', how='left')

# Calculate their order value
dropped_orders['order_value'] = (
    dropped_orders['quantity'] * dropped_orders['price'] * (1 - dropped_orders['discount_pct'] / 100)
)

print("DUPLICATE ORDER VALUE REMOVED:", round(dropped_orders['order_value'].sum(), 2))

