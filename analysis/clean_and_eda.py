##	Task 10 - Outlier-corrected time series

# 1. Convert order_date to datetime, extract year-month, compute monthly total order_value with outlier:
orders_clean['order_date'] = pd.to_datetime(orders_clean['order_date'])
orders_clean['year_month'] = orders_clean['order_date'].dt.to_period('M')

monthly_order_value = orders_clean.groupby('year_month')['order_value'].sum().round(2)

