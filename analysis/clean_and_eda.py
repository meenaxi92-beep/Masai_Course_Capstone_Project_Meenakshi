print(monthly_order_value) ## Including the outliers and extreme values

# 2. Monthly order value excluding outliers
o2_corrected_monthly_order_value = (orders_clean[~orders_clean['is_outlier']]
    .groupby('year_month')['order_value'].sum().round(2)
)

print("\n-- Monthly Order Value Excluding Outliers --")
