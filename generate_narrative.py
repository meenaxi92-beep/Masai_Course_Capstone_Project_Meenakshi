## 4.	Task 4 - Offline fallback path

def generate_scr_narrative_offline(findings: dict) -> dict:
    """
    Generate an SCR narrative locally without an API call.
    Uses verified values from findings.json.
    """

    cleaned_revenue = findings["cleaned_total_revenue_inr"]
    raw_revenue = findings["raw_total_revenue_inr"]
    reconciliation_delta = findings["duplicate_reconciliation_delta_inr"]

    payment_rates = findings["return_rate_by_payment"]
    highest_risk = findings["highest_risk_segment"]
    peak_month = findings["true_peak_month"]
    inflated_month = findings["outlier_inflated_month"]

    cod_value_rates = findings["cod_return_rate_by_value"]

    tier_value_data = findings["cod_return_rate_by_tier_and_value"]

    tier2_high_value = next(
        item for item in tier_value_data
        if item["city_tier"] == 2
        and item["value_group"] == "High Value"
    )

    narrative = f"""
SITUATION

The Mamaearth Returns & Growth Intelligence Pipeline established a cleaned
revenue baseline of INR {cleaned_revenue:,.2f}, compared with raw revenue of
INR {raw_revenue:,.2f}. The analysis evaluates payment-method return patterns
and monthly revenue trends.

COMPLICATION

Duplicate records account for a reconciliation difference of
INR {reconciliation_delta:,.2f}. Return rates vary by payment method:
COD {payment_rates['COD']:.1f}%, CARD {payment_rates['CARD']:.1f}%,
and UPI {payment_rates['UPI']:.1f}%. The highest-risk segment is
{highest_risk['payment_method']} in Tier {highest_risk['city_tier']} cities,
with a return rate of {highest_risk['return_rate_pct']:.1f}%.
High-value COD orders in Tier 2 cities show a return rate of
{tier2_high_value['return_rate_pct']:.1f}%:
{tier2_high_value['returned_orders']} returns out of
{tier2_high_value['total_orders']} orders.

RESOLUTION

After correcting for the revenue outlier, {peak_month['month']} was the
true peak month, with revenue of INR {peak_month['revenue_inr']:,.2f}.
The apparent peak in {inflated_month['month']} was INR
{inflated_month['apparent_revenue_inr']:,.2f}, compared with corrected
revenue of INR {inflated_month['corrected_revenue_inr']:,.2f}.
A suitable next step is to pilot interventions for high-value COD orders
in Tier 2 cities and validate the observed pattern with additional data.
""".strip()

    return {
        "status": "success",
        "narrative": narrative,
        "tokens": 0
    }

